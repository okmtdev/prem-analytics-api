/** Translate `key` for `lang`, filling `{placeholders}` from `vars`. */
export function t(lang, key, vars = {}) {
  const dict = STR[lang] ?? STR.en;
  let s = dict[key] ?? STR.en[key] ?? key;
  for (const [k, v] of Object.entries(vars)) {
    s = s.replaceAll(`{${k}}`, v === null || v === undefined ? dict.na : String(v));
  }
  return s;
}

/** Ordinal for English ("1st") or 「位」 for Japanese. */
export function ordinal(lang, n) {
  if (n === null || n === undefined) return STR[lang]?.na ?? "–";
  if (lang === "ja") return `${n}位`;
  const s = ["th", "st", "nd", "rd"];
  const v = n % 100;
  return `${n}${s[(v - 20) % 10] ?? s[v] ?? s[0]}`;
}
